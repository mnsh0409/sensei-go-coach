"""Render README.md and video_script.md from their templates (TASKS.md T10).

    python scripts/render_readme.py              # README.tmpl.md -> README.md, video_script.tmpl.md -> video_script.md
    python scripts/render_readme.py --results results --root .

The templates hold `{{token}}`s (eval/tokens.py) inside `<!-- results -->` ... `<!-- /results -->` blocks. Only
clean result files resolve (git_dirty false, a real commit), so a dirty run can never reach the README. Every
output starts with a comment naming its template and the result files it used. Edit the template, never the
output; `scripts/check_numbers.py` fails when an output differs from a fresh rendering.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Sequence
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from eval.tokens import Resolver, TokenError, render_blocks  # noqa: E402

PAIRS = (("README.tmpl.md", "README.md"), ("video_script.tmpl.md", "video_script.md"))
HEADER = (
    "<!-- Generated by scripts/render_readme.py from {template}; edit the template, not this file. "
    "Results: {files}. -->\n"
)


def render_file(template: Path, resolver: Resolver) -> str:
    """The full output text for one template: header plus the template with its result blocks rendered."""
    body = render_blocks(template.read_text(encoding="utf-8"), resolver)
    files = ", ".join(f"{k}={v}" for k, v in sorted(resolver.files.items())) or "none"
    return HEADER.format(template=template.name, files=files) + body


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=str(ROOT), help="directory holding the templates and outputs")
    ap.add_argument("--results", default=None, help="results directory (default: <root>/results)")
    args = ap.parse_args(argv)
    root = Path(args.root)
    resolver = Resolver(Path(args.results) if args.results else root / "results")
    rendered = 0
    for template_name, output_name in PAIRS:
        template = root / template_name
        if not template.is_file():
            print(f"skip {template_name}: not written yet")
            continue
        try:
            text = render_file(template, resolver)
        except TokenError as err:
            print(f"error in {template_name}: {err}", file=sys.stderr)
            return 1
        (root / output_name).write_text(text, encoding="utf-8")
        print(f"wrote {output_name} from {template_name}")
        rendered += 1
    if not rendered:
        print("no template found: create README.tmpl.md (TASKS.md T10)", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
